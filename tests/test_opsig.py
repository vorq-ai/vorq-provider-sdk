"""``vorqd.opsig`` against the vectors the contracts themselves produced.

``tests/vectors/signing-v3.json`` is generated by
``vorq-evm-contracts/test/Vectors.t.sol``: every case is signed over the digest
derived from its own published payload and is then handed to the deployed
contract and accepted. It is the authority here — every expected value below is
**read out of the file**, never restated, so a change to the contracts' types or
domains fails these tests rather than agreeing with a stale copy.

The strongest assertions are the ones that recover the file's own signature
through this SDK's encoding. The private keys are deliberately absent from the
file, so recovery — not re-signing — is what proves that direction.
"""

from __future__ import annotations

import inspect
import json
from dataclasses import replace

import pytest
from eth_account import Account
from eth_utils import keccak

from vorqd import opsig
from vorqd._crypto import SESSION_TYPES, WalletSigner, vorq_domain
from vorqd.escrow import RELEASE_TYPES, release_domain
from vorqd.money import format_usd
from vorqd.opsig import OpSigner
from vorqd.types import ChainContext

from .vectors import ADDRESSES, CASES, DOMAINS, VECTORS, coerce, local_types, message, typed_data

#: The artifacts this daemon signs. The file also carries the client's half
#: (Order, Cancel, the payment authorization); those are the client SDK's to check.
OP_CASES = [
    "claim",
    "settle",
    "fail",
    "set-identity",
    "set-identity-empty-evidence",
    "request-capacity",
]
ASK_CASES = ["ask-snapshot", "ask-snapshot-empty"]
#: Every case this repo signs, including the two artifacts no contract verifies.
SIGNED_CASES = OP_CASES + ASK_CASES + ["release", "session"]


#: The payment token's decimals: the vectors' rates are atomic at USDC's six.
DECIMALS = 6


def chain_context() -> ChainContext:
    """The deployment the vectors were generated against."""
    return ChainContext(
        chain_id=VECTORS["chain_id"],
        job_registry=ADDRESSES["job_registry"],
        provider_registry=ADDRESSES["provider_registry"],
        ask_registry=ADDRESSES["ask_registry"],
        usdc=ADDRESSES["payment_token"],
        decimals=DECIMALS,
    )


def primary_of(name: str) -> str:
    return CASES[name]["typed_data"]["primaryType"]


def our_typed_data(name: str) -> dict:
    """The case rebuilt through :mod:`vorqd.opsig` rather than read from the file."""
    return opsig.typed_data(primary_of(name), message(name), chain_context())


