def test_absent_evidence_signs_as_empty_bytes(op_signer: OpSigner) -> None:
    """``None`` and ``0x`` are the same op — and both hash, never zero-pad."""
    ctx = chain_context()
    msg = message("set-identity-empty-evidence")
    assert msg["evidence"] == b""
    assert op_signer.sign_set_identity(msg["boxKey"], None, msg["issuedAt"], ctx) == (
        op_signer.sign_set_identity(msg["boxKey"], b"", msg["issuedAt"], ctx)
    )
    assert CASES["set-identity-empty-evidence"]["extra"]["evidence_hash"] == "0x" + keccak(b"").hex()


def test_the_coercion_is_driven_by_the_declared_type(op_signer: OpSigner) -> None:
    """Sanity on the loader itself: widths that a JSON double would round come back
    as exact integers, and byte members as bytes."""
    assert isinstance(message("claim")["jobId"], bytes)
    assert isinstance(message("set-identity")["evidence"], bytes)
    assert all(isinstance(q["rateIn"], int) for q in message("ask-snapshot")["quotes"])
    assert coerce({"T": [{"name": "v", "type": "uint128"}]}, "T", {"v": "340282366920938463463374607431768211455"})[
        "v"
    ] == 2**128 - 1
