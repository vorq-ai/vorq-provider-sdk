@pytest.mark.parametrize(
    ("name", "wrong_field"),
    [("request-capacity", "job_registry"), ("ask-snapshot", "job_registry"), ("claim", "ask_registry")],
)
def test_a_wrong_verifying_contract_recovers_a_stranger(name: str, wrong_field: str) -> None:
    """The failure mode this whole file exists for, made loud.

    The three VORQ domains share a name, a version and a chain id and differ only
    in ``verifyingContract``. A wrong one produces a **silently invalid**
    signature rather than an error: ``setAsks`` skips the entry, the registries
    refuse it, and nothing anywhere says why. So the assertion is not that
    something raises — it is that the recovered address is a stranger.
    """
    ctx = chain_context()
    field = opsig.SIGNED_REGISTRY[primary_of(name)]
    confused = replace(ctx, **{field: getattr(ctx, wrong_field)})

    wrong = opsig.typed_data(primary_of(name), message(name), confused)
    assert opsig.digest(wrong) != CASES[name]["digest"]

    stranger = opsig.recover(wrong, CASES[name]["signature"])
    assert stranger != CASES[name]["signer"]


def test_the_three_domains_differ_at_all() -> None:
    """Without this the confusion cases above would prove nothing."""
    separators = {DOMAINS[k]["separator"] for k in ("job_registry", "provider_registry", "ask_registry")}
    assert len(separators) == 3

    ctx = chain_context()
    for primary, expected in {
        "Claim": ctx.job_registry,
        "Settle": ctx.job_registry,
        "Fail": ctx.job_registry,
        "SetIdentity": ctx.provider_registry,
        "RequestCapacity": ctx.provider_registry,
        "AskSnapshot": ctx.ask_registry,
    }.items():
        assert opsig.domain_for(primary, ctx)["verifyingContract"] == expected


def test_the_off_chain_domains_name_no_contract() -> None:
    """Release and VorqSession have no verifying contract at all — three domain
    members, not four — and the file says so with a null separator rather than a
    zero word a consumer might compare against."""
    for key in ("escrow", "session"):
        assert DOMAINS[key]["separator"] is None
        assert "verifyingContract" not in DOMAINS[key]["domain"]


def test_the_domain_is_never_a_parameter() -> None:
    """No ``sign_*`` takes a domain, an address or a type string.

    The defence is structural: a caller that cannot state a domain cannot state
    the wrong one.
    """
    for name, method in inspect.getmembers(OpSigner, inspect.isfunction):
        if not name.startswith("sign_"):
            continue
        params = set(inspect.signature(method).parameters)
        assert not params & {"domain", "verifying_contract", "contract", "types", "primary_type"}
        assert "ctx" in params


