@pytest.mark.parametrize("name", OP_CASES + ASK_CASES)
def test_our_type_table_is_the_one_the_contract_verifies(name: str) -> None:
    """Direct list equality against the published table.

    A member renamed, retyped or reordered changes the typehash, which changes
    the digest, which makes the signature recover a different address — and the
    contract refuses it with no error that names the cause. The published table
    is the one a signature the contract ACCEPTED was built from, so agreeing with
    it is the whole check; there is no derived type string to compare.
    """
    assert opsig.SIGNED_TYPES[primary_of(name)] == local_types(name)


def test_the_release_type_table_matches_the_vector() -> None:
    """No contract verifies a Release, so this file and the coordinator are the
    only two places it exists. That is exactly why it needs a vector."""
    assert RELEASE_TYPES == local_types("release")


def test_the_session_type_table_matches_the_vector() -> None:
    assert SESSION_TYPES == local_types("session")


def test_no_op_type_carries_a_cid() -> None:
    """``Settle`` attests the delivered count and nothing about which bytes produced it."""
    for members in opsig.OP_TYPES.values():
        for struct in members.values():
            assert not any("cid" in member["name"].lower() for member in struct)


