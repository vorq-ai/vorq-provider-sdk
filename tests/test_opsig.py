def test_the_ask_snapshot_is_not_an_op() -> None:
    """It is signed here, and it does **not** go through ``POST /evm/ops``.

    A whole book replaces a whole book at ``PUT /evm/asks``; the ops door relays
    one act at a time. Keeping ``AskSnapshot`` out of ``OP_NAMES`` is what stops
    a caller pushing it to the wrong door and getting a `400` for a reason that
    names nothing.
    """
    assert "AskSnapshot" not in opsig.OP_NAMES
    assert "AskSnapshot" not in opsig.OP_TYPES
    assert "AskSnapshot" in opsig.SIGNED_TYPES
    assert opsig.SIGNED_REGISTRY["AskSnapshot"] == "ask_registry"
    assert set(opsig.OP_TYPES) < set(opsig.SIGNED_TYPES)


def test_a_withdrawal_rides_as_rate_out_zero_and_is_signed_like_any_other_quote() -> None:
    """A withdrawn slot is a quote, not an omission (``AskRegistry.setAsks``).

    On chain the write is an upsert: a slot the snapshot omits keeps its previous
    price forever. Only ``rateOut == 0`` deletes one — so the withdrawal has to be
    inside the signed struct. The vector carries one, and the contracts' own
    acceptance test reads the emptied slot back through ``getQuote``.
    """
    quotes = message("ask-snapshot")["quotes"]
    assert any(q["rateOut"] == 0 for q in quotes)

    without = {**wire_snapshot("ask-snapshot"), "quotes": wire_snapshot("ask-snapshot")["quotes"][:1]}
    ctx = chain_context()
    assert opsig.digest(
        opsig.typed_data("AskSnapshot", opsig.ask_snapshot_message(without, DECIMALS), ctx)
    ) != CASES["ask-snapshot"]["digest"]


def test_an_empty_snapshot_is_signable() -> None:
    """The all-withdrawn book a drain pushes still hashes: ``keccak256("")`` of no
    element hashes is a real value, not a zero word."""
    assert message("ask-snapshot-empty")["quotes"] == []
    assert opsig.digest(our_typed_data("ask-snapshot-empty")) == CASES["ask-snapshot-empty"]["digest"]


def test_the_snapshot_is_signed_from_the_wire_body_itself() -> None:
    """The wire body survives a JSON round trip, and signing carries the full widths."""
    snap = wire_snapshot("ask-snapshot")
    assert opsig.ask_snapshot_message(snap, DECIMALS) == opsig.ask_snapshot_message(
        json.loads(json.dumps(snap)), DECIMALS)

    huge = {
        "provider_id": 7,
        "signed_at": 2**64 - 1,
        "quotes": [
            {
                "model_id": 1,
                "sla": 3600,
                "rate_in": format_usd(2**128 - 1, DECIMALS),
                "rate_out": "0.000001",
            }
        ],
    }
    assert opsig.ask_snapshot_message(huge, DECIMALS)["signedAt"] == 2**64 - 1
    assert opsig.ask_snapshot_message(huge, DECIMALS)["quotes"][0]["rateIn"] == 2**128 - 1
    assert opsig.ask_snapshot_message(huge, DECIMALS)["quotes"][0]["rateOut"] == 1


#: The secp256k1 group order. A canonical signature carries `s <= N // 2`; the
#: twin at `N - s` recovers the same address, which is what makes signature bytes
#: unusable as an identity.
SECP256K1_N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141


@pytest.mark.parametrize("name", OP_CASES)
def test_every_signature_this_daemon_produces_is_canonical(name: str, op_signer: OpSigner) -> None:
    """Low-`s`, and `v` in {27, 28}, on every op the daemon authorises.

    **The registries do not enforce this and never will.** `JobRegistry._recover`
    and `ProviderRegistry._recover` call bare `ecrecover` with no canonical-`s`
    bound, so the high-`s` twin `(r, N - s, 55 - v)` of any signature below
    recovers the same operator address and is accepted just as readily. That is
    deliberate: replay is stopped by the job state machine and by the monotonic
    `issuedAt` floors, never by signature bytes.

    The rule it leaves on this side is one line — **a signature is never an
    identifier** — and this is what keeps it true rather than incidental to
    whichever `eth-account` is installed.
    """
    raw = bytes.fromhex(signed_for(name, op_signer)[2:])
    assert len(raw) == 65
    s = int.from_bytes(raw[32:64], "big")
    assert 0 < s <= SECP256K1_N // 2, f"{name} carries a high-s signature"
    assert raw[64] in (27, 28), f"{name} carries v={raw[64]}, which recovers address(0)"


def test_the_ask_snapshot_signature_is_canonical_too(op_signer: OpSigner) -> None:
    """The third domain, held to the same rule as the five ops.

    Signed here rather than on `WalletSigner` (the module docstring says why), so
    it is the one signature that could drift away from the others without any of
    the parametrized cases above noticing.
    """
    # `wire_snapshot("ask-snapshot")` returns the vector's own book in wire shape;
    # a hand-built one would work too, but this keeps one source for the fields.
    raw = bytes.fromhex(
        op_signer.sign_ask_snapshot(wire_snapshot("ask-snapshot"), chain_context())[2:]
    )
    assert len(raw) == 65
    assert 0 < int.from_bytes(raw[32:64], "big") <= SECP256K1_N // 2
    assert raw[64] in (27, 28)


def test_the_high_s_twin_recovers_the_same_operator(op_signer: OpSigner) -> None:
    """Why the rule above is a rule, demonstrated once.

    Different bytes, same digest, same recovered address — so a node that
    deduplicated relayed ops on the signature would relay the same claim twice
    and pay gas for the second one.
    """
    raw = bytes.fromhex(signed_for("claim", op_signer)[2:])
    twin = (
        raw[0:32]
        + (SECP256K1_N - int.from_bytes(raw[32:64], "big")).to_bytes(32, "big")
        # 27 <-> 28. Not `v ^ 1`: that is the {0, 1} recovery-id convention, and
        # it takes 27 to 26, which `eth-account` refuses outright.
        + bytes([55 - raw[64]])
    )

    assert twin != raw
    assert opsig.recover(our_typed_data("claim"), "0x" + twin.hex()) == op_signer.address


