@pytest.fixture
def op_signer() -> OpSigner:
    return OpSigner(WalletSigner.generate())


def signed_for(name: str, signer: OpSigner) -> str:
    """Sign the vector case's fields through the public ``sign_*`` method."""
    ctx, msg, primary = chain_context(), message(name), primary_of(name)
    if primary == "Claim":
        return signer.sign_claim(msg["jobId"], msg["issuedAt"], ctx)
    if primary == "Settle":
        return signer.sign_settle(msg["jobId"], msg["completionTok"], msg["issuedAt"], ctx)
    if primary == "Fail":
        return signer.sign_fail(msg["jobId"], msg["issuedAt"], ctx)
    if primary == "SetIdentity":
        return signer.sign_set_identity(msg["boxKey"], msg["evidence"], msg["issuedAt"], ctx)
    return signer.sign_request_capacity(msg["n"], msg["issuedAt"], ctx)


@pytest.mark.parametrize("name", OP_CASES)
def test_sign_round_trips_over_the_vector_typed_data(name: str, op_signer: OpSigner) -> None:
    """Our signature recovers our own address **over the vector's typed data**.

    That is what ties the ``sign_*`` methods to the digests above: a method that
    signed some other domain or some other member order would recover a
    different address here.
    """
    signature = signed_for(name, op_signer)
    assert opsig.recover(typed_data(name), signature) == op_signer.address
    assert Account._recover_hash(CASES[name]["digest"], signature=signature) == op_signer.address


@pytest.mark.parametrize("name", ASK_CASES)
def test_the_ask_snapshot_round_trips_through_its_signer(name: str, op_signer: OpSigner) -> None:
    """The one assertion the chain makes: ``idOf(ecrecover(...)) == providerId``.

    ``ask_snapshot_message`` takes the wire body itself, so the snapshot signed
    and the snapshot pushed cannot come apart.
    """
    signature = op_signer.sign_ask_snapshot(wire_snapshot(name), chain_context())
    assert opsig.recover(typed_data(name), signature) == op_signer.address


def wire_snapshot(name: str) -> dict:
    """The vector's snapshot in the shape ``PUT /evm/asks`` carries it.

    The rates as USD decimal strings, every other member a JSON integer.
    """
    msg = message(name)
    return {
        "provider_id": int(msg["providerId"]),
        "signed_at": int(msg["signedAt"]),
        "quotes": [
            {
                "model_id": int(q["modelId"]),
                "sla": int(q["sla"]),
                "rate_in": format_usd(int(q["rateIn"]), DECIMALS),
                "rate_out": format_usd(int(q["rateOut"]), DECIMALS),
            }
            for q in msg["quotes"]
        ],
    }


@pytest.mark.parametrize("name", ASK_CASES)
def test_the_wire_snapshot_signs_to_the_vector_digest(name: str) -> None:
    """The wire body in, the digest out — the snapshot pushed is the one signed."""
    data = opsig.typed_data(
        "AskSnapshot", opsig.ask_snapshot_message(wire_snapshot(name), DECIMALS), chain_context()
    )
    assert opsig.digest(data) == CASES[name]["digest"]


def test_a_job_id_hex_string_signs_the_same_as_bytes(op_signer: OpSigner) -> None:
    raw = CASES["claim"]["typed_data"]["message"]
    as_hex = op_signer.sign_claim(raw["jobId"], raw["issuedAt"], chain_context())
    assert opsig.recover(typed_data("claim"), as_hex) == op_signer.address


def test_claim_and_fail_have_identical_members_but_different_digests() -> None:
    """Only the type NAME separates them, which is exactly what makes this dangerous.

    No table-equality assertion can catch a signer that reuses one type for the
    other: the member lists are identical. Only the digests differ.
    """
    assert message("claim") == message("fail")
    assert CASES["claim"]["digest"] != CASES["fail"]["digest"]
    assert opsig.digest(our_typed_data("claim")) != opsig.digest(our_typed_data("fail"))


